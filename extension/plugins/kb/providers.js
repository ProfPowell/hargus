/** First matching label for a value (or null). */
export function classify(table, value = '') {
  for (const [re, label, kind] of table) {
    const m = String(value).match(re);
    if (m) return { label: typeof label === 'function' ? label(m) : label, kind };
  }
  return null;
}

/** Unique labels matched by any of the values. */
export function classifyAll(table, values = []) {
  const out = new Set();
  for (const v of values) {
    const c = classify(table, v);
    if (c) out.add(c.label);
  }
  return [...out];
}
